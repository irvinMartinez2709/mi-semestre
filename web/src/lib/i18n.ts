export interface Traducciones {
  es: Record<string, string>;
  en: Record<string, string>;
}

export const TRADUCCIONES: Record<Idioma, Record<string, string>> = {
  es,
  en,
};

export const DIAS_LARGO_IDIOMA: Record<Idioma, string[]> = {
  es: [
    "Domingo",
    "Lunes",
    "Martes",
    "Miércoles",
    "Jueves",
    "Viernes",
    "Sábado",
  ],
  en: [
    "Sunday",
    "Monday",
    "Tuesday",
    "Wednesday",
    "Thursday",
    "Friday",
    "Saturday",
  ],
};

export const DIAS_CORTO_IDIOMA: Record<Idioma, string[]> = {
  es: ["dom", "lun", "mar", "mié", "jue", "vie", "sáb"],
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
};

export function traducir(
  idioma: Idioma,
  clave: string,
  ...args: (string | number)[]
): string {
  const dict = TRADUCCIONES[idioma];
  let texto = dict[clave] ?? clave;
  texto = texto.replace(
    /\{(\d+), plural, one \{([^}]*)\} other \{([^}]*)\}\}/g,
    (_t, idx, uno, otros) => {
      const n = Number(args[parseInt(idx, 10)]);
      return (n === 1 ? uno : otros).replace("#", String(n));
    }
  );
  args.forEach((a, i) => {
    texto = texto.replace(`{${i}}`, String(a));
  });
  return texto;
}